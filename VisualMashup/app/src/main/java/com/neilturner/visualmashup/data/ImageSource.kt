package com.neilturner.visualmashup.data

/** The orientation of a [SourceImage], derived from its dimensions. */
enum class ImageOrientation {
    LANDSCAPE,
    PORTRAIT,
    SQUARE,
}

/**
 * A single 1080p test image.
 *
 * [width] and [height] are the pixel dimensions the image is served at.
 */
data class SourceImage(
    val id: Int,
    val url: String,
    val width: Int,
    val height: Int,
    val orientation: ImageOrientation,
)

